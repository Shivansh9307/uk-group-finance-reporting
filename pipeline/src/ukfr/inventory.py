"""The inventory of every assertion the build is checked by, generated from the files.

`sql/tests/*.sql` are the data invariants (one query each, zero rows passes). The Python tests that
read the built database and assert controls live in `pipeline/tests/`. Both lists are read from the
files here, so the table in `docs/reconciliation.md` cannot drift from them: `ukfr inventory` prints it
and fails when a SQL test has no `-- test:` header or when the document's block differs from what the
files say, and `ukfr inventory --write` rewrites the block.

Scope of a SQL test:
- `committed`: runs on a build from the files in git, which is what CI builds;
- `full`: needs a full-scope build (`-- requires:` objects that only a full build creates, or
  `-- marker: localdata` for files outside git). CI skips these; a local full build runs them.

The evidence file is the file in `evidence/` that the test reads, found by the `audit.<table>` names in
its text; a test that has none reads the warehouse directly and its evidence is the query itself.
"""

from __future__ import annotations

import ast
import re
from dataclasses import dataclass
from pathlib import Path

from . import sqlrunner

DOC = Path("docs") / "reconciliation.md"
BEGIN = "<!-- inventory:begin (generated by `ukfr inventory --write`; do not edit by hand) -->"
END = "<!-- inventory:end -->"
_AUDIT_REF = re.compile(r"\baudit\.([a-z_0-9]+)", re.IGNORECASE)
_CSV_REF = re.compile(r"\b((?:data|evidence|docs)/[A-Za-z0-9_./-]+\.csv)\b")


@dataclass(frozen=True)
class SqlAssertion:
    ident: str
    name: str
    proves: str
    scope: str
    marker: str
    evidence: str


@dataclass(frozen=True)
class PyAssertion:
    ident: str
    name: str
    proves: str
    scope: str
    marker: str
    evidence: str


def _evidence_for(root: Path, text: str) -> str:
    found: list[str] = []
    for table in sorted({m.group(1).lower() for m in _AUDIT_REF.finditer(text)}):
        for folder in ("build", "full"):
            rel = f"evidence/{folder}/{table}.csv"
            if (root / rel).is_file():
                found.append(rel)
                break
    for rel in sorted({m.group(1) for m in _CSV_REF.finditer(text)}):
        if (root / rel).is_file():
            found.append(rel)
    return ", ".join(found) if found else "none (query on the warehouse)"


def sql_assertions(root: Path) -> tuple[list[SqlAssertion], list[str]]:
    """Every file under `sql/tests/`, and the problems found (a missing `-- test:` header, an id used twice)."""
    out: list[SqlAssertion] = []
    problems: list[str] = []
    seen: dict[str, str] = {}
    for path in sqlrunner.collect_test_files(root / "sql"):
        text = path.read_text(encoding="utf-8")
        d = sqlrunner.header_directives(text)
        rel = path.relative_to(root).as_posix()
        if not d.get("test"):
            problems.append(f"{rel}: no '-- test: ...' header in the first lines")
        ident = path.stem.split("_", 1)[0]
        if ident in seen:
            problems.append(f"{rel}: id {ident} is also used by {seen[ident]}")
        seen[ident] = rel
        marker = d.get("marker", "")
        requires = d.get("requires", "")
        scope = "full" if marker == "localdata" or requires else "committed"
        out.append(
            SqlAssertion(
                ident=ident,
                name=path.stem,
                proves=d.get("test", ""),
                scope=scope,
                marker=marker or ("requires " + requires if requires else ""),
                evidence=_evidence_for(root, text),
            )
        )
    return out, problems


def _markers(decorators: list[ast.expr]) -> set[str]:
    names: set[str] = set()
    for dec in decorators:
        node = dec.func if isinstance(dec, ast.Call) else dec
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Attribute) and node.value.attr == "mark":
            names.add(node.attr)
    return names


def _module_markers(tree: ast.Module) -> set[str]:
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "pytestmark" for t in node.targets):
            value = node.value
            items = value.elts if isinstance(value, ast.List | ast.Tuple) else [value]
            names |= _markers(list(items))
    return names


def python_assertions(root: Path) -> list[PyAssertion]:
    """Test functions that read the built database (marker `db`, directly or for the whole module)."""
    out: list[PyAssertion] = []
    for path in sorted((root / "pipeline" / "tests").glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        module_marks = _module_markers(tree)
        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef) or not node.name.startswith("test_"):
                continue
            marks = _markers(node.decorator_list) | module_marks
            if "db" not in marks:
                continue
            doc = ast.get_docstring(node)
            proves = doc.strip().splitlines()[0] if doc else node.name.removeprefix("test_").replace("_", " ")
            scope = "full" if "localdata" in marks else "committed"
            out.append(
                PyAssertion(
                    ident=f"{path.stem}::{node.name}",
                    name=node.name,
                    proves=proves,
                    scope=scope,
                    marker="localdata" if "localdata" in marks else "",
                    evidence=_evidence_for(root, ast.get_source_segment(path.read_text(encoding="utf-8"), node) or ""),
                )
            )
    return out


def problems(root: Path) -> list[str]:
    found = sql_assertions(root)[1]
    doc = root / DOC
    if doc.is_file():
        text = doc.read_text(encoding="utf-8").replace("\r\n", "\n")
        if BEGIN not in text or END not in text:
            found.append(f"{DOC.as_posix()}: the inventory block markers are missing")
        elif _block(text) != render_markdown(root):
            found.append(f"{DOC.as_posix()}: the inventory block is out of date; run `ukfr inventory --write`")
    else:
        found.append(f"{DOC.as_posix()} does not exist")
    return found


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def where_runs(scope: str) -> str:
    return "CI (pipeline-sql) and local builds" if scope == "committed" else "local full build only"


def render_markdown(root: Path) -> str:
    sql, _ = sql_assertions(root)
    py = python_assertions(root)
    lines = [
        f"{len(sql)} SQL assertions ({sum(a.scope == 'committed' for a in sql)} committed scope, "
        f"{sum(a.scope == 'full' for a in sql)} full scope) and {len(py)} Python assertions that read the built "
        f"database ({sum(a.scope == 'committed' for a in py)} committed scope, "
        f"{sum(a.scope == 'full' for a in py)} full scope).",
        "",
        "### SQL assertions (`sql/tests/`)",
        "",
        "| Id | What it proves | Scope | Marker | Where it runs | Evidence file |",
        "|---|---|---|---|---|---|",
    ]
    for a in sql:
        lines.append(
            f"| `{a.ident}` | {_cell(a.proves)} | {a.scope} | {_cell(a.marker) or '-'} | {where_runs(a.scope)} | "
            f"{_cell(a.evidence)} |"
        )
    lines += [
        "",
        "### Python assertions that read the built database (`pipeline/tests/`)",
        "",
        "| Test | What it proves | Scope | Marker | Where it runs | Evidence file |",
        "|---|---|---|---|---|---|",
    ]
    for p in py:
        lines.append(
            f"| `{p.ident}` | {_cell(p.proves)} | {p.scope} | {_cell(p.marker) or '-'} | {where_runs(p.scope)} | "
            f"{_cell(p.evidence)} |"
        )
    return "\n".join(lines) + "\n"


def render_text(root: Path) -> str:
    """The list as plain lines for a build log: id, scope, marker, what it proves."""
    sql, _ = sql_assertions(root)
    lines = [f"{len(sql)} SQL assertions in sql/tests:"]
    for a in sql:
        lines.append(f"  {a.ident:>4}  {a.scope:9} {a.marker or '-':32} {a.proves[:110]}")
    py = python_assertions(root)
    lines.append(f"{len(py)} Python assertions that read the built database:")
    for p in py:
        lines.append(f"  {p.scope:9} {p.marker or '-':10} {p.ident}")
    return "\n".join(lines)


def _block(text: str) -> str:
    start = text.index(BEGIN) + len(BEGIN)
    return text[start : text.index(END)].strip("\n") + "\n"


def write_doc(root: Path) -> Path:
    path = root / DOC
    raw = path.read_text(encoding="utf-8")
    crlf = "\r\n" in raw
    text = raw.replace("\r\n", "\n")
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    new = head + BEGIN + "\n\n" + render_markdown(root) + "\n" + END + tail
    path.write_text(new.replace("\n", "\r\n") if crlf else new, encoding="utf-8", newline="")
    return path
