"""Expected values for the model tests whose truth is a published file, not a warehouse table.

The deflators and the ONS price series are read by the model over the web (Power Query, from the links in
data/manifest/files.csv). The expected values here are read from the pinned local copies with `ukfr.readers.deflators`,
after the copies are checked against the sha256 recorded in the manifest. So a DAX test that compares the two proves
that the file the model downloaded holds the values of the file in the manifest.

The ONS files are regenerated by the publisher each month and are marked volatile in the manifest: the local copy can
be older than the web copy. The tests therefore compare the months the pinned copy holds (to 2026-09-01, held as a
literal in the DAX tests; the expected-value generator fails if the pinned files end elsewhere) and leave later
months alone.
"""

from __future__ import annotations

from decimal import Decimal
from pathlib import Path

from .config import FILES_CSV, data_dir
from .fetch import resolve
from .http import sha256_file
from .manifest import Row, read_rows
from .readers import deflators


def _pinned(root: Path, source_id: str) -> list[tuple[Row, Path]]:
    raw = data_dir(root)
    out = []
    for r in read_rows(root / FILES_CSV):
        if r.source_id != source_id or r.fetched != "yes":
            continue
        path = resolve(root, raw, r.path)
        if not path.is_file():
            raise FileNotFoundError(f"{r.path} is not under {raw}: run `ukfr fetch` or set UKFR_DATA_DIR")
        out.append((r, path))
    return sorted(out, key=lambda t: (t[0].release, t[0].filename))


def _check_hash(row: Row, path: Path) -> None:
    got = sha256_file(path)
    if got != row.sha256:
        raise ValueError(f"{path.name} does not match the sha256 in the manifest ({got} != {row.sha256})")


def deflator_values(root: Path) -> list[dict]:
    """Every financial year of every pinned GDP deflator vintage, with the chained index."""
    out = []
    for row, path in _pinned(root, "gdp_deflator"):
        _check_hash(row, path)
        d = deflators.read_gdp_deflator(path)
        chained = deflators.chained_index(d)
        for y in d.years:
            out.append(
                {
                    "vintage_id": row.release,
                    "financial_year": y.year,
                    "year_status": "Forecast" if y.forecast else "Outturn",
                    "index_published": y.index,
                    "per_cent_change": y.pct_change,
                    "chained_index": chained[y.year],
                }
            )
    return out


def cpi_values(root: Path) -> tuple[list[dict], str]:
    """Monthly rows of the pinned ONS files and the latest month they hold ('2026-09-01')."""
    out = []
    latest = ""
    for _row, path in _pinned(root, "ons_cpi"):
        s = deflators.read_ons_series(path)  # parses by the shape of each line and fails on anything else
        series_id = s.meta["CDID"]
        for label, value in s.monthly:
            y, m = deflators.month_key(label)
            month = f"{y:04d}-{m:02d}-01"
            latest = max(latest, month)
            out.append({"series_id": series_id, "month": month, "value": value})
    return out, latest


# Real terms: the default vintage of the model's Deflator table and the price base of the real-terms measures.
DEFAULT_DEFLATOR_VINTAGE = "2026-10-budget"
REAL_BASE_YEAR = "2025-26"


def real_terms_index(root: Path) -> dict[str, Decimal]:
    """Financial year -> chained index of the default vintage, read from the pinned workbook."""
    return {
        d["financial_year"]: d["chained_index"]
        for d in deflator_values(root)
        if d["vintage_id"] == DEFAULT_DEFLATOR_VINTAGE
    }


def real_terms_factors(root: Path) -> dict[str, Decimal]:
    """Financial year -> index of the base year divided by the index of the year: what an amount of that year is
    multiplied by to be in 2025-26 prices."""
    index = real_terms_index(root)
    base = index[REAL_BASE_YEAR]
    return {year: base / value for year, value in index.items()}
